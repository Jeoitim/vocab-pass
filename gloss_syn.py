def canon(token):
    """归一化一个释义片段：去掉「的」，统一写法。"""
    t = token.strip()
    for suf in ("的", "地", "了"):
        if len(t) > 2 and t.endswith(suf):
            t = t[:-1]
            break
    return t


def expand(token):
    """返回该 token 的同义组内所有写法（含自身）。"""
    t = canon(token)
    out = {t}
    for gi in TOKEN2GROUP.get(t, ()):
        out.update(canon(x) for x in GROUP_TOKENS[gi])
    return out


# 构建 token -> 组号 的索引（原始写法与 canon 写法都建索引）
def _build_index():
    idx = {}
    for gi, line in enumerate(GROUPS):
        for tok in line.split():
            idx.setdefault(tok, set()).add(gi)
            c = canon(tok)
            if c != tok:
                idx.setdefault(c, set()).add(gi)
    return idx


TOKEN2GROUP = _build_index()
GROUP_TOKENS = [line.split() for line in GROUPS]
